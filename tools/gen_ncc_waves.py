"""NCC's WAVE engine's wavetables (firmware/src/eng_wave.c) -> a C header.

  tools/gen_ncc_waves.py OUT.h

Worked out here, no recordings and no other instrument's data: five tables of eight single-cycle waves, which the
engine's POS knob moves through (between two neighbours at a time):
  BASIC   a sine opening into a saw (a low-pass on the saw's harmonics, further open each wave)
  VOX     a buzz through two formants that move up: vowel-like
  GLASS   a sine phase-modulated by its third harmonic, deeper each wave: bells, glass, FM colours
  PULSE   a pulse from square to a thin 3 %
  SYNC    a windowed sine of 1 to 4.5 times the pitch: an oscillator sync sweep

Each wave as its first 64 harmonics, then written four times with fewer of them (64, 24, 9, 3: the engine takes
the one that stays below half the sample rate at the note it plays), 256 samples (+ the first again: the engine
reads between two) of 8 bits, every level of a wave at the one scale that brings its fullest level to +-127.
"""
import math
import sys
from pathlib import Path

N = 256                      # samples a wave
P = 2048                     # points of the prototype a wave's harmonics are taken from
HARM = (64, 24, 9, 3)        # harmonics kept per level (eng_wave.c wave_level)
TABLES = ("BASIC", "VOX", "GLASS", "PULSE", "SYNC")
WAVES = 8


def proto(table, k):
    """wave k (0..7) of a table as P points of one cycle"""
    x = [2.0 * math.pi * i / P for i in range(P)]
    if table == "BASIC":
        cut = (1.0, 1.6, 2.5, 4.0, 7.0, 12.0, 24.0, 64.0)[k]
        return [sum(math.sin(n * a) / n / (1.0 + (n / cut) ** 4) for n in range(1, 65)) for a in x]
    if table == "VOX":
        f1, f2 = 2.0 + k, 6.0 + 18.0 * k / 7.0

        def amp(n):
            g1 = 1.0 / (1.0 + ((n - f1) / (1.0 + f1 / 6.0)) ** 2)
            g2 = 1.0 / (1.0 + ((n - f2) / (1.0 + f2 / 6.0)) ** 2)
            return (g1 + 0.6 * g2 + (0.3 if n == 1 else 0.0)) / math.sqrt(n)
        return [sum(amp(n) * math.sin(n * a) for n in range(1, 65)) for a in x]
    if table == "GLASS":
        depth = 5.0 * k / 7.0
        return [math.sin(a + depth * math.sin(3.0 * a)) for a in x]
    if table == "PULSE":
        duty = (0.5, 0.4, 0.3, 0.22, 0.15, 0.10, 0.06, 0.03)[k]
        return [sum(math.sin(n * math.pi * duty) / n * math.cos(n * a) for n in range(1, 65)) for a in x]
    ratio = 1.0 + 3.5 * k / 7.0                       # SYNC
    return [math.sin(ratio * a) * (1.0 - a / (2.0 * math.pi)) for a in x]


def harmonics(w):
    """the sine and cosine parts of harmonics 1..64 of one cycle w"""
    out = []
    for n in range(1, 65):
        s = sum(v * math.sin(2.0 * math.pi * n * i / P) for i, v in enumerate(w)) * 2.0 / P
        c = sum(v * math.cos(2.0 * math.pi * n * i / P) for i, v in enumerate(w)) * 2.0 / P
        out.append((s, c))
    return out


def levels(h):
    """the wave of harmonics h at each level: N samples of -127..127"""
    raw = []
    for top in HARM:
        raw.append([sum(s * math.sin(2.0 * math.pi * (n + 1) * i / N) + c * math.cos(2.0 * math.pi * (n + 1) * i / N)
                        for n, (s, c) in enumerate(h[:top])) for i in range(N)])
    peak = max(max(abs(v) for v in r) for r in raw) or 1.0
    return [[max(-127, min(127, round(v * 127.0 / peak))) for v in r] for r in raw]


def main(path):
    L = ["/* generated by tools/gen_ncc_waves.py: NCC's WAVE engine's wavetables (eng_wave.c) */",
         "#pragma once", "#include <stdint.h>",
         f"#define NW_TABLES {len(TABLES)}", f"#define NW_WAVES {WAVES}", f"#define NW_LEVELS {len(HARM)}",
         f"#define NW_LEN {N}",
         "static const int8_t NCC_WAVES[NW_TABLES][NW_WAVES][NW_LEVELS][NW_LEN + 1] = {"]
    for t in TABLES:
        L.append(f"    {{   /* {t} */")
        for k in range(WAVES):
            L.append("        {")
            for lv in levels(harmonics(proto(t, k))):
                row = lv + lv[:1]
                L.append("            {" + ", ".join(str(v) for v in row) + "},")
            L.append("        },")
        L.append("    },")
    L += ["};"]
    Path(path).write_text("\n".join(L) + "\n")
    print(f"ncc waves: {len(TABLES)} tables x {WAVES} waves x {len(HARM)} levels -> {path}")


if __name__ == "__main__":
    main(sys.argv[1])
