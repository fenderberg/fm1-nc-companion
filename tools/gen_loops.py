def render(hits, swing):
    """one bar of hits at gs.TR (float samples), the tails wrapped round"""
    src = gs.gm_kit_sources()
    n = int(round(gs.TR * 60 / BPM * 4))
    x = [0.0] * n
    pos = [s * n // STEPS for s in range(STEPS + 1)]
    sw = int(swing * (n // 16))                     # the off 16ths late by swing of a 16th
    for step, role, gain in hits:
        if role not in src:
            continue
        smp = gs.gm_kit_entry(role, src[role])
        at = pos[step] + (sw if step % 4 == 2 else 0)
        if role == "ohh":
            nxt = min([s for s, r, _ in hits if r in ("chh", "ohh") and s > step] or [STEPS])
            keep, fade = pos[nxt] - pos[step], int(0.004 * gs.TR)
            smp = [v * min(1.0, (keep - i) / fade) for i, v in enumerate(smp[:keep])]
        for i, v in enumerate(smp):
            x[(at + i) % n] += v * gain
    return x


def lofi(x):
    """gs.TR -> RATE (an average of each pair: a gentle low-pass first), 8 bits signed at -1 dBFS"""
    step = gs.TR // RATE
    y = [sum(x[i:i + step]) / step for i in range(0, len(x) - step + 1, step)]
    pk = max(1e-9, max(abs(v) for v in y))
    return [max(-127, min(127, int(round(v * 113 / pk)))) for v in y]


def main(out):
    subprocess.run([sys.executable, str(Path(__file__).with_name("gen_waves.py")), str(WAVDIR)], check=True,
                   stdout=subprocess.DEVNULL)
    gs.GENDIR = WAVDIR
    data, offs = [], [0]
    for name, swing, hits in LOOPS:
        data += lofi(render(hits, swing))
        offs.append(len(data))
    L = ["/* generated by tools/gen_loops.py: NCC's LOOP engine's drum loops (eng_loop.c) */",
         f"#define NLOOP {len(LOOPS)}", f"#define NLOOP_RATE {RATE}", f"#define NLOOP_BPM {BPM}",
         "#define NLOOP_NAMES " + ", ".join(f'"{n}"' for n, _, _ in LOOPS),
         "static const char *const NLOOP_NAME[NLOOP + 1] = {NLOOP_NAMES, 0};",
         "static const uint32_t NLOOP_OFF[NLOOP + 1] = {" + ", ".join(map(str, offs)) + "};",
         f"static const int8_t NLOOP_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        L.append("    " + ", ".join(map(str, data[i:i + 24])) + ",")
    L.append("};")
    Path(out).write_text("\n".join(L) + "\n")
    print(f"loops: {len(LOOPS)}, {len(data)} B ({RATE} Hz, 8 bits) -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
